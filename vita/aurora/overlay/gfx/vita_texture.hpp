// Vita backend: GL texture objects (vitaGL / GLES2). Everything here must be called on the thread
// that owns the GL context unless noted otherwise.
//
// Texture contents:
//   - Static textures (GX_TF_* formats, TLUTs) are decoded on the CPU to RGBA8 and uploaded.
//   - EFB copy destinations (new_render_texture / new_conv_texture) are empty RGBA8 textures that the
//     replay renders into; the replay owns the format conversion of the copy.
//   - A palette-indexed EFB copy (TP's map: copy as R8, sample as C8) is a "derived" texture: it is
//     computed on the GPU from the copy texture and a TLUT texture the first time a draw samples it
//     after the copy was rewritten (see prepare_texture_for_sampling).
//
// GL state touched by the creation functions: they bind GL_TEXTURE_2D on the *currently active* texture
// unit and change GL_UNPACK_ALIGNMENT. The replay must not assume that its cached binding of that unit
// survives between frames.
#pragma once

#include "texture.hpp"

namespace aurora::gfx {

// A texture computed from `src` (an 8-bit-or-4-bit index in the red channel, as an EFB copy in GX_CTF_R8 /
// GX_CTF_R4 leaves it) and the RGBA8 palette texture `tlut`: dst(x,y) = tlut[src(x,y).r].
struct PaletteDerivation {
  TextureHandle src;
  TextureHandle tlut;
  bool fourBit = false;
  bool converted = false;
  uint32_t convertedSerial = 0; // src->contentSerial the current contents were computed from
};

// New RGBA8 texture of `width` x `height` whose contents derive from `src` + `tlut`.
TextureHandle new_palette_derived_texture(TextureHandle src, TextureHandle tlut, bool fourBit, const char* label) noexcept;
// Points a derived texture at a different TLUT texture and schedules a recompute.
void update_palette_derivation(TextureRef& dst, TextureHandle tlut) noexcept;

// REPLAY: call after rendering into a texture (an EFB copy resolve), so derived textures notice.
void mark_texture_written(TextureRef& ref) noexcept;

// REPLAY: call for every texture a draw binds, before binding it. Returns true when a GPU pass ran to
// refresh a derived texture. That pass clobbers GL state (framebuffer binding, viewport, scissor/depth/
// blend/cull enables, current program, vertex attrib arrays, active texture unit and its binding): the
// framebuffer binding is restored to `restoreFramebuffer`, everything else the caller must re-establish.
bool prepare_texture_for_sampling(TextureRef& ref, uint32_t restoreFramebuffer = 0) noexcept;

// REPLAY: applies `sampler` to the GL texture currently bound to GL_TEXTURE_2D on the active unit
// (wrap modes, min/mag filter; a mip filter degrades to its non-mip form when the texture has no mip
// levels). Only issues glTexParameteri for values that differ from ref's cached state. LOD bias and
// min/max LOD have no GLES2 equivalent and are ignored.
void apply_sampler(TextureRef& ref, const SamplerDesc& sampler) noexcept;

// REPLAY: deletes GL objects (textures and FBOs) of TextureRefs that were destroyed since the last call.
// TextureRef destructors only queue the ids, so they are safe on any thread.
void flush_texture_deletions() noexcept;

// Releases the empty texture, scratch memory and helper programs, then flushes pending deletions.
void shutdown_textures() noexcept;

// 1x1 transparent black RGBA8 (what upstream binds for an unbound/missing texture). Created on first use.
TextureHandle empty_texture() noexcept;

// Uploads already-decoded RGBA8 pixels (levels concatenated, level n is max(w>>n,1) x max(h>>n,1); the
// pointer is 4-byte aligned). Missing levels of a power-of-two chain are generated by box filtering.
// Non-power-of-two textures keep only level 0. Returns null on failure (size, out of memory).
TextureHandle new_texture_rgba8(uint32_t width, uint32_t height, uint32_t levels, const uint32_t* pixels,
                                u32 gxFormat, const char* label) noexcept;

// Bytes of GL memory a texture occupies (RGBA8, all levels), and the running total of live textures.
uint64_t texture_gpu_bytes(const TextureRef& ref) noexcept;
uint64_t live_texture_bytes() noexcept;

// TLUT format <-> the GX texture format its entries are decoded like (upstream naming).
inline GXTexFmt tlut_texture_format(GXTlutFmt format) noexcept {
  switch (format) {
  case GX_TL_RGB565:
    return GX_TF_RGB565;
  case GX_TL_RGB5A3:
    return GX_TF_RGB5A3;
  case GX_TL_IA8:
  default:
    return GX_TF_IA8;
  }
}

} // namespace aurora::gfx
